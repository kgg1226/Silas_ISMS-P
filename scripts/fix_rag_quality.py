# ──────────────────────────────────────────────────────
# 4. DE 형식 불일치 수정 (2.10.6, 3.1.6)
# ──────────────────────────────────────────────────────
DE_FORMAT_FIX = ["2.10.6", "3.1.6"]


def main():
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row

    stats = {"dc": 0, "kc": 0, "de": 0, "de_fmt": 0}

    # --- DC 수정 ---
    print("\n=== 결함사례(DC) 15건 수정 ===")
    for code, defects in DC_FIX.items():
        dc_json = json.dumps(defects, ensure_ascii=False)
        conn.execute(
            "UPDATE isms_requirements SET defect_cases = ? WHERE item_code = ?",
            (dc_json, code),
        )
        stats["dc"] += 1
        print(f"  DC {code}: {len(defects)}건")

    # --- KC 수정 ---
    print("\n=== 주요확인사항(KC) 12건 수정 ===")
    for code, checks in KC_FIX.items():
        kc_json = json.dumps(checks, ensure_ascii=False)
        conn.execute(
            "UPDATE isms_requirements SET key_checks = ? WHERE item_code = ?",
            (kc_json, code),
        )
        stats["kc"] += 1
        print(f"  KC {code}: {len(checks)}건")

    # --- DE 보강 ---
    print("\n=== 상세설명(DE) 12건 보강 ===")
    for code, explanations in DE_FIX.items():
        de_json = json.dumps(explanations, ensure_ascii=False)
        conn.execute(
            "UPDATE isms_requirements SET detailed_explanation = ? WHERE item_code = ?",
            (de_json, code),
        )
        stats["de"] += 1
        print(f"  DE {code}: {len(explanations)}건")

    # --- DE 형식 수정 ---
    print("\n=== DE 형식 불일치 2건 수정 ===")
    for code in DE_FORMAT_FIX:
        row = conn.execute(
            "SELECT detailed_explanation FROM isms_requirements WHERE item_code = ?",
            (code,),
        ).fetchone()
        de_raw = row["detailed_explanation"] or ""
        try:
            parsed = json.loads(de_raw)
        except (json.JSONDecodeError, TypeError):
            print(f"  {code}: 파싱 실패, 스킵")
            continue

        if isinstance(parsed, dict):
            # dict의 모든 값을 평탄화하여 배열로
            flat = []
            for key, val in parsed.items():
                if isinstance(val, list):
                    flat.extend([f"[{key}] {v}" for v in val if isinstance(v, str)])
                elif isinstance(val, dict):
                    for k2, v2 in val.items():
                        if isinstance(v2, list):
                            flat.extend(
                                [f"[{key}/{k2}] {v}" for v in v2 if isinstance(v, str)]
                            )
                        elif isinstance(v2, str):
                            flat.append(f"[{key}/{k2}] {v2}")
                elif isinstance(val, str):
                    flat.append(f"[{key}] {val}")
            de_json = json.dumps(flat, ensure_ascii=False)
            conn.execute(
                "UPDATE isms_requirements SET detailed_explanation = ? WHERE item_code = ?",
                (de_json, code),
            )
            stats["de_fmt"] += 1
            print(f"  {code}: dict → array ({len(flat)}항목)")
        else:
            print(f"  {code}: 이미 array 형태, 스킵")

    conn.commit()
    conn.close()

    print(f"\n{'='*50}")
    print(f"DC 수정: {stats['dc']}건")
    print(f"KC 수정: {stats['kc']}건")
    print(f"DE 보강: {stats['de']}건")
    print(f"DE 형식: {stats['de_fmt']}건")
    print("완료")


if __name__ == "__main__":
    main()
