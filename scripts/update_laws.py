def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    updated = 0
    for code, laws in LAW_MAP.items():
        laws_json = json.dumps(laws, ensure_ascii=False)
        cur.execute(
            "UPDATE isms_requirements SET related_laws = ? WHERE item_code = ?",
            (laws_json, code),
        )
        if cur.rowcount > 0:
            updated += 1
            print(f"  ✅ {code}: {len(laws)}개 법령 매핑")
        else:
            print(f"  ⚠️  {code}: 항목 없음 (rowcount=0)")

    conn.commit()

    # 검증
    cur.execute(
        "SELECT COUNT(*) FROM isms_requirements "
        "WHERE related_laws IS NOT NULL AND related_laws != '' AND related_laws != '[]'"
    )
    mapped = cur.fetchone()[0]

    cur.execute("SELECT COUNT(*) FROM isms_requirements")
    total = cur.fetchone()[0]

    print(f"\n{'='*50}")
    print(f"업데이트: {updated}건")
    print(f"법령 매핑: {mapped}/{total} ({mapped/total*100:.1f}%)")

    # 남은 누락 확인
    cur.execute(
        "SELECT item_code, item_title FROM isms_requirements "
        "WHERE related_laws IS NULL OR related_laws = '' OR related_laws = '[]' "
        "ORDER BY item_code"
    )
    remaining = cur.fetchall()
    if remaining:
        print(f"\n아직 누락: {len(remaining)}건")
        for r in remaining:
            print(f"  {r[0]} | {r[1]}")
    else:
        print("\n✅ 전체 101개 항목 법령 매핑 완료!")

    conn.close()


if __name__ == "__main__":
    main()
